function minutesOf(chapter) {
  const chars = chapter.paragraphs.join('').replace(/\s+/g, '').length;
  return Math.max(1, Math.round(chars / 380));
}

BOOK.chapters.forEach(function (chapter) {
  chapter.minutes = minutesOf(chapter);
});
